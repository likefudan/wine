"""Turn TTB's list of American Viticultural Areas into src/shared/ava.ts.

The list is US government public data. COLA Cloud publishes it as a CSV:
  curl -o ava.csv https://dyuie4zgfxmt6.cloudfront.net/open-data/ttb_viticultural_areas.csv
  python3 scripts/ava_import.py ava.csv src/shared/ava.ts

Each AVA gets the region people usually write beside it: an AVA with AVAs inside it
is its own region (Napa Valley); otherwise its smallest parent AVA (Oakville -> Napa
Valley, Eola-Amity Hills -> Willamette Valley), or else its state.
"""

import csv
import json
import sys

STATES = {
    "AL": "Alabama", "AK": "Alaska", "AZ": "Arizona", "AR": "Arkansas", "CA": "California",
    "CO": "Colorado", "CT": "Connecticut", "DE": "Delaware", "FL": "Florida", "GA": "Georgia",
    "HI": "Hawaii", "ID": "Idaho", "IL": "Illinois", "IN": "Indiana", "IA": "Iowa", "KS": "Kansas",
    "KY": "Kentucky", "LA": "Louisiana", "ME": "Maine", "MD": "Maryland", "MA": "Massachusetts",
    "MI": "Michigan", "MN": "Minnesota", "MS": "Mississippi", "MO": "Missouri", "MT": "Montana",
    "NE": "Nebraska", "NV": "Nevada", "NH": "New Hampshire", "NJ": "New Jersey", "NM": "New Mexico",
    "NY": "New York", "NC": "North Carolina", "ND": "North Dakota", "OH": "Ohio", "OK": "Oklahoma",
    "OR": "Oregon", "PA": "Pennsylvania", "RI": "Rhode Island", "SC": "South Carolina",
    "SD": "South Dakota", "TN": "Tennessee", "TX": "Texas", "UT": "Utah", "VT": "Vermont",
    "VA": "Virginia", "WA": "Washington", "WV": "West Virginia", "WI": "Wisconsin", "WY": "Wyoming",
}


CODES = {v: k for k, v in STATES.items()}


def listed(s):
    s = (s or "").strip()
    return json.loads(s) if s.startswith("[") else []


def main(src, out):
    avas = {}
    for r in csv.DictReader(open(src, encoding="utf-8-sig")):
        if r["removed_date"].strip():
            continue
        # The file can hold several versions of one AVA; the last one wins.
        avas[r["name"].strip()] = {
            "states": [CODES.get(x.strip(), x.strip()) for x in listed(r["states"])],
            "parents": [p.strip() for p in listed(r["parent_avas"])],
            "children": [c.strip() for c in listed(r["child_avas"])],
        }
    kids = {n: len(a["children"]) for n, a in avas.items()}

    def ancestors(n, seen=None):
        seen = set() if seen is None else seen
        for p in avas.get(n, {}).get("parents", []):
            if p in avas and p not in seen:
                seen.add(p)
                ancestors(p, seen)
        return seen
    rows = []
    for name in sorted(avas, key=str.lower):
        a = avas[name]
        parents = [p for p in a["parents"] if p in avas]
        if kids[name]:
            region = name
        elif parents:
            # Only the parents not inside another parent; an AVA across two of them
            # (Los Carneros: Napa Valley and Sonoma Valley) gets no region.
            inner = [p for p in parents if not any(p in ancestors(q) for q in parents if q != p)]
            region = inner[0] if len(inner) == 1 else ""
        else:
            region = STATES.get(a["states"][0], "") if len(a["states"]) == 1 else ""
        rows.append([name, region, ",".join(a["states"])])
    body = "\n".join(f"  {json.dumps(r, ensure_ascii=False)}," for r in rows)
    open(out, "w").write(
        "// Generated by scripts/ava_import.py from TTB's list of American Viticultural Areas\n"
        "// (US government public data). Do not edit by hand.\n\n"
        "/** [AVA, the region usually written with it, states] */\n"
        f"export const AVAS: readonly (readonly [string, string, string])[] = [\n{body}\n];\n\n"
        "export const AVA_NAMES = AVAS.map((a) => a[0]);\n\n"
        "const byName = new Map(AVAS.map((a) => [a[0].toLowerCase(), a]));\n\n"
        "/** The AVA with exactly this name (any case), with its usual region and states. */\n"
        "export function avaOf(name: string): { name: string; region: string; states: string[] } | null {\n"
        "  const a = byName.get(name.trim().toLowerCase());\n"
        "  return a ? { name: a[0], region: a[1], states: a[2].split(\",\") } : null;\n"
        "}\n"
    )
    print(len(rows), "AVAs")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
