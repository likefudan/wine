/**
 * 香气词表: one vocabulary for my notes, friends' notes and (later) the critics', so they can be
 * compared across languages (docs/design.zh.md §1, §3.8). A note stores the id; each language shows
 * its own word. Families and words follow the WSET Wine-Lexicon (Level 3 clusters; each word says
 * whether the Level 2 and/or Level 3 lexicon lists it: 入门 offers the L2 words, 进阶 the L3 ones).
 * Words that are in neither are kept only so old notes still read; no picker offers them. The
 * plain-language hints are our own. zh-TW uses Taiwan wine vocabulary, not a character swap.
 *
 * Ids are permanent: rename a word freely, never reuse or change an id.
 */

export type Tri = { zh: string; tw: string; en: string };

export interface Family {
  id: string;
  tier: 1 | 2 | 3;
  name: Tri;
}

export interface Descriptor {
  id: string;
  family: string;
  name: Tri;
  /** A everyday thing it smells like, for 入门 (empty when the word says it already). */
  hint?: Tri;
  /** Which colours of wine usually show it: the pickers list these first. */
  for?: ("red" | "white")[];
  /** The WSET lexicons that list it; empty for an old word no picker offers any more. */
  wset: Level[];
  /** Other families WSET also lists it under (toast is yeast, oak and bottle age). */
  also?: string[];
}

/** WSET Level 2 (入门) or Level 3 (进阶). */
export type Level = "L2" | "L3";

