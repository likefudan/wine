/** Whether a word belongs to one of these families, its own or one WSET also lists it under. */
const inFamilies = (d: Descriptor, families: string[]) =>
  families.includes(d.family) || !!d.also?.some((f) => families.includes(f));

/**
 * The words of some families that a level's lexicon lists, the ones usual for this colour of wine
 * first.
 */
export function wordsOf(families: string[], color: "red" | "white", level: Level): Descriptor[] {
  const words = DESCRIPTORS.filter((d) => d.wset.includes(level) && inFamilies(d, families));
  const usual = (d: Descriptor) => !d.for || d.for.includes(color);
  return [...words.filter(usual), ...words.filter((d) => !usual(d))];
}
