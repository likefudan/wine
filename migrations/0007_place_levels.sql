-- Producers that can move: region is a known place below a big region, and each of their wines has no
-- 子产区, that same place, or a place inside it (Oakville under Napa Valley).
CREATE TABLE place_fix_producers AS
  SELECT p.id, f.name, f.region, lower(f.name) AS lname FROM producers p JOIN place_fix f ON f.k = lower(trim(p.region))
  WHERE f.region <> '' AND lower(f.region) <> f.k AND NOT EXISTS (
    SELECT 1 FROM wines w
    LEFT JOIN place_fix a ON a.k = lower(trim(w.appellation))
    WHERE w.producer_id = p.id AND trim(coalesce(w.appellation, '')) <> ''
      AND lower(trim(w.appellation)) <> f.k
      AND lower(coalesce(a.name, '')) <> lower(f.name)
      AND lower(coalesce(a.area, '')) <> lower(f.name)
  );

UPDATE wines SET appellation = (SELECT name FROM place_fix_producers x WHERE x.id = wines.producer_id)
WHERE trim(coalesce(appellation, '')) = '' AND producer_id IN (SELECT id FROM place_fix_producers);

UPDATE producers SET region = (SELECT region FROM place_fix_producers x WHERE x.id = producers.id)
WHERE id IN (SELECT id FROM place_fix_producers);

-- One spelling for the USA (LWIN says "United States", the 子产区 list said "USA").
UPDATE producers SET country = 'USA'
WHERE lower(trim(country)) IN ('us', 'united states', 'united states of america', 'america', '美国', '美國');

