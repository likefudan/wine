-- A producer whose 产区 is really a 大区 (Sonoma County, Napa Valley): its wines get that 大区 (unless their
-- 子产区 says otherwise) and the producer the big region above, when every wine agrees, so nothing is lost.
CREATE TABLE area_fix_producers AS
  SELECT p.id, f.name, f.region FROM producers p JOIN area_fix_area f ON f.k = lower(trim(p.region))
  WHERE NOT EXISTS (
    SELECT 1 FROM wines w LEFT JOIN area_fix_app a ON a.k = lower(trim(w.appellation))
    WHERE w.producer_id = p.id AND trim(coalesce(w.appellation, '')) <> ''
      AND lower(trim(w.appellation)) <> f.k AND lower(coalesce(a.area, '')) <> lower(f.name)
  );
UPDATE wines SET area = (SELECT name FROM area_fix_producers x WHERE x.id = wines.producer_id)
WHERE producer_id IN (SELECT id FROM area_fix_producers);
UPDATE producers SET region = (SELECT region FROM area_fix_producers x WHERE x.id = producers.id)
WHERE id IN (SELECT id FROM area_fix_producers);

-- Every other wine: the 大区 of its 子产区, when its producer's 产区 is that 大区's big region or empty.
UPDATE wines SET area = (SELECT a.area FROM area_fix_app a WHERE a.k = lower(trim(wines.appellation)))
WHERE area IS NULL AND lower(trim(appellation)) IN (SELECT k FROM area_fix_app)
  AND (SELECT coalesce(lower(trim(p.region)), '') FROM producers p WHERE p.id = wines.producer_id)
      IN ('', (SELECT lower(a.region) FROM area_fix_app a WHERE a.k = lower(trim(wines.appellation))));

